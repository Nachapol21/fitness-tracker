/**
 * วางแผน seed อาหาร: existing = อาหารทั้งหมดในเครื่อง (รวมที่ soft delete — ของที่ผู้ใช้ลบไปแล้วไม่ถูกเอากลับมา)
 * คืน { add: [แถวที่ต้องเพิ่ม], skipped: [{name, reason:'seed'|'user'|'extra'}] }
 *  - อาหารตั้งต้นชุดเดิม: ข้ามเฉพาะ id ที่มีอยู่แล้ว (พฤติกรรมเดิม)
 *  - เมนูเพิ่มเติม: ข้ามถ้า id มีอยู่แล้ว หรือชื่อซ้ำ (normText: ตัดช่องว่าง วงเล็บ ตัวพิมพ์) กับ
 *    อาหารตั้งต้นเดิม ('seed') หรืออาหารที่ผู้ใช้สร้างเอง/มีในเครื่อง ('user') หรือเมนูเพิ่มเติมที่ชื่อซ้ำกันเอง
 */
export function planFoodSeed(existing = []) {
  const ids = new Set(existing.map((f) => f.id));
  const base = seedFoods();
  const source = new Map(); // ชื่อที่ normalize แล้ว → ที่มา ('user' < 'seed' < 'extra' ตามลำดับที่ลงทะเบียน)
  for (const f of existing) source.set(normText(f.name), 'user');
  for (const f of base) source.set(normText(f.name), 'seed'); // ชื่อซ้ำกับอาหารตั้งต้นเดิม ให้บอกว่าซ้ำกับ seed
  const add = base.filter((f) => !ids.has(f.id));
  const skipped = [];
  for (const f of seedFoodsExtra()) {
    const n = normText(f.name);
    if (source.has(n)) {
      skipped.push({ name: f.name, reason: source.get(n) });
      continue;
    }
    source.set(n, 'extra');
    if (!ids.has(f.id)) add.push(f);
  }
  return { add, skipped };
}

export function seedRewards() {
  return REWARDS.map(([emoji, name, price, kcal, cooldown_days]) => ({
    ...base(seedId('reward', name)),
    name,
    emoji,
    price,
    kcal,
    cooldown_days,
    active: true,
  }));
}

export const exerciseIdByName = (name) => seedId('exercise', name);
