function base(id) {
  return { id, created_at: SEED_TIME, updated_at: SEED_TIME, deleted: false };
}

export function seedExercises() {
  return EXERCISES.map(([name, muscle, category, equipment, rep_min, rep_max, extra = {}]) => ({
    ...base(seedId('exercise', name)),
    name,
    muscle,
    category,
    equipment,
    machine: extra.machine || '',
    rep_min,
    rep_max,
    timed: !!extra.timed,
    per_side: !!extra.per_side,
    note: extra.note || '',
  }));
}

export function seedFoods() {
  return FOODS.map(([name, serving, kcal, protein, carb, fat, fav]) => ({
    ...base(seedId('food', name)),
    name,
    serving,
    kcal,
    protein,
    carb,
    fat,
    favorite: !!fav,
    estimated: true, // ค่าประมาณ แต่ละร้านต่างกันได้ ±20–30%
  }));
}

